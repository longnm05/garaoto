CREATE DATABASE IF NOT EXISTS garaoto CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE garaoto;

DROP TABLE IF EXISTS bang_luong;
DROP TABLE IF EXISTS phieu_tiep_nhan;
DROP TABLE IF EXISTS nhan_vien;

CREATE TABLE nhan_vien (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ma_nv VARCHAR(20) NOT NULL UNIQUE,
    ho_ten VARCHAR(100) NOT NULL,
    luong_cung DECIMAL(12, 0) NOT NULL DEFAULT 0,
    don_gia_cong DECIMAL(12, 0) NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE phieu_tiep_nhan (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ma_phieu VARCHAR(20) NOT NULL UNIQUE,
    nhan_vien_id INT UNSIGNED NOT NULL,
    ngay_hoan_thanh DATE NULL,
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'Chưa hoàn thành',
    CONSTRAINT fk_ptn_nhan_vien FOREIGN KEY (nhan_vien_id) REFERENCES nhan_vien(id)
) ENGINE=InnoDB;

CREATE TABLE bang_luong (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nhan_vien_id INT UNSIGNED NOT NULL,
    thang TINYINT UNSIGNED NOT NULL,
    nam SMALLINT UNSIGNED NOT NULL,
    so_cong INT UNSIGNED NOT NULL DEFAULT 0,
    tien_cong DECIMAL(12, 0) NOT NULL DEFAULT 0,
    thuong DECIMAL(12, 0) NOT NULL DEFAULT 0,
    phat DECIMAL(12, 0) NOT NULL DEFAULT 0,
    tam_ung DECIMAL(12, 0) NOT NULL DEFAULT 0,
    tong_luong DECIMAL(12, 0) NOT NULL DEFAULT 0,
    da_chot TINYINT(1) NOT NULL DEFAULT 0,
    UNIQUE KEY uq_bang_luong_ky (nhan_vien_id, thang, nam),
    CONSTRAINT fk_bang_luong_nhan_vien FOREIGN KEY (nhan_vien_id) REFERENCES nhan_vien(id)
) ENGINE=InnoDB;

